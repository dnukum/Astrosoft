#!/bin/bash
set -euo pipefail

# ==============================================================================
# Astrosoft Release Publisher - Pre-Flight Verification & Packaging Script
# ==============================================================================
# Guarantees that:
# 1. Source code compiles cleanly from scratch.
# 2. 'bin/AstroSoft.jar' is freshly packaged with the latest compiled bytecode.
# 3. 'resources/version.properties' matches the manifest inside 'bin/AstroSoft.jar'.
# 4. All headless regression tests pass with 100% success.
# ==============================================================================

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(git -C "$SCRIPT_DIR" rev-parse --show-toplevel 2>/dev/null || true)"
if [ -z "$REPO_ROOT" ]; then
    REPO_ROOT="$(cd "$SCRIPT_DIR/../../../.." && pwd)"
fi
cd "$REPO_ROOT"

echo "========================================================================"
echo " [Astrosoft Release Publisher] Pre-Flight Verification & Packaging"
echo "========================================================================"

# Step 1: Run headless regression smoke suite
echo "==> Step 1/4: Running Astrosoft UI smoke regression suite..."
./.agents/skills/astrosoft-regression-guardian/scripts/run_ui_smoke.sh

# Step 2: Clean build and package runnable archive
echo "==> Step 2/4: Building clean deploy and packaging bin/AstroSoft.jar..."
ant clean deploy

# Step 3: Verify bin/AstroSoft.jar existence and timestamp consistency
echo "==> Step 3/4: Verifying bin/AstroSoft.jar bytecode and version sync..."
if [ ! -f "bin/AstroSoft.jar" ]; then
    echo "❌ ERROR: bin/AstroSoft.jar was not generated by ant deploy!" >&2
    exit 1
fi

JAR_VERSION=$(unzip -p bin/AstroSoft.jar resources/version.properties 2>/dev/null | grep "build.version=" | cut -d'=' -f2 || true)
SRC_VERSION=$(grep "build.version=" resources/version.properties 2>/dev/null | cut -d'=' -f2 || true)

if [ -z "$JAR_VERSION" ] || [ -z "$SRC_VERSION" ]; then
    echo "❌ ERROR: Could not resolve build version string from archive or resources!" >&2
    exit 1
fi

if [ "$JAR_VERSION" != "$SRC_VERSION" ]; then
    echo "❌ ERROR: Version mismatch between archive and source!" >&2
    echo "   bin/AstroSoft.jar version     : $JAR_VERSION" >&2
    echo "   resources/version.properties : $SRC_VERSION" >&2
    exit 1
fi
echo "   ✅ Version timestamp verified: $JAR_VERSION"

# Step 4: Verify critical UI & Diagnostic classes exist in archive
echo "==> Step 4/4: Verifying core modern classes in bin/AstroSoft.jar..."
REQUIRED_CLASSES=(
    "app/astrosoft/ui/AstroSoft.class"
    "app/astrosoft/ui/dlg/DiagnosticsDialog.class"
    "app/astrosoft/ui/util/SystemDiagnostics.class"
    "app/astrosoft/ui/dlg/AshtavargaDialog.class"
    "app/astrosoft/ui/dlg/PlanetDetailsDialog.class"
    "app/astrosoft/ui/dlg/HouseDetailsDialog.class"
    "app/astrosoft/ui/dlg/TransitChartDialog.class"
    "app/astrosoft/ui/table/AstrosoftTable.class"
)

for cls in "${REQUIRED_CLASSES[@]}"; do
    if ! unzip -l bin/AstroSoft.jar "$cls" >/dev/null 2>&1; then
        echo "❌ ERROR: Missing required class in bin/AstroSoft.jar: $cls" >&2
        exit 1
    fi
done
echo "   ✅ All modern inspection and diagnostics classes present in archive."

echo "========================================================================"
echo " ✅ SUCCESS: Pre-flight packaging and verification PASSED!"
echo "    Archive 'bin/AstroSoft.jar' is verified, fresh, and ready to publish."
echo "========================================================================"
